// build-wordmark.mjs: turns the word CIVIC into drawn shapes for the club's logo.
//
// What this does, in plain words:
// Our logo is the word CIVIC set very large in the Host Grotesk typeface, in its Light weight.
// Instead of relying on the browser to draw the letters from a font file, we trace each letter
// once, here, into an SVG "path" (a list of drawing instructions: move here, curve to there).
// That way the logo looks identical everywhere, and the animation code can move each letter
// on its own (the two Cs land first, then the two Is, then the V).
//
// Where the information comes from: the Host Grotesk Light font file that ships inside the
// @fontsource/host-grotesk package in node_modules (the font is free under the OFL license,
// which allows turning letters into outlines for a logo).
// Where it goes: it writes two files.
//   1. src/components/Wordmark.astro: the logo component every page uses.
//   2. src/assets/brand/wordmark.svg: a plain copy used by scripts/build-brand-images.mjs
//      to make the share image and favicon.
//
// Run it with: npm run wordmark   (only needed if you change the letters, font or spacing).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';
import { toPathData } from './lib/path-data.mjs';

// Work out where the project folder is, so the script works from any folder you run it in.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

// The settings for the logo. Change these, run the script again, and the logo updates.
// WORD is the text. TRACKING is the extra space between letters as a share of the font size:
// -0.04 means "pull every pair of letters 4% of the font size closer together".
const WORD = 'CIVIC';
const TRACKING = -0.04;
const FONT_FILE = resolve(
  root,
  'node_modules/@fontsource/host-grotesk/files/host-grotesk-latin-300-normal.woff'
);

// Load the font file. opentype.js wants the raw bytes as an "ArrayBuffer" (a block of memory),
// so we copy the file's bytes into one before handing them over.
const bytes = readFileSync(FONT_FILE);
const font = opentype.parse(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength));

// We draw at a size equal to the font's own design grid (usually 1000 units per letter height),
// so every number below is in the font's native units and nothing gets rounded away.
const size = font.unitsPerEm;
const trackingUnits = TRACKING * size;

// Round a number to one decimal place. The paths are huge on screen, but one decimal is still
// far finer than a single pixel, and it keeps the file small.
const round = (n) => Math.round(n * 10) / 10;

// Go through the word one letter at a time, placing each letter to the right of the one before.
// For each letter we keep its drawing instructions and the box it fills (its "bounding box").
const letters = [];
let penX = 0;
const glyphs = font.stringToGlyphs(WORD);
glyphs.forEach((glyph, i) => {
  // Draw the letter with its baseline at 0. In SVG, y grows downwards, so the top of a
  // capital letter ends up at a negative y (about -700) and the baseline sits at y = 0.
  const path = glyph.getPath(penX, 0, size);
  const box = path.getBoundingBox();
  letters.push({ char: WORD[i], path, box });

  // Move the pen to where the next letter starts: this letter's width, plus the font's
  // built-in "kerning" for this pair of letters (small spacing fixes the type designer made),
  // plus our own tighter tracking.
  const next = glyphs[i + 1];
  const kern = next ? font.getKerningValue(glyph, next) : 0;
  penX += glyph.advanceWidth + kern + (next ? trackingUnits : 0);
});

// Find the smallest box that holds every letter. This becomes the SVG "viewBox" (the visible
// window onto the drawing), so the logo has no empty space around it and can run exactly
// from one page margin to the other.
const minX = Math.min(...letters.map((l) => l.box.x1));
const minY = Math.min(...letters.map((l) => l.box.y1));
const maxX = Math.max(...letters.map((l) => l.box.x2));
const maxY = Math.max(...letters.map((l) => l.box.y2));
const viewBox = [round(minX), round(minY), round(maxX - minX), round(maxY - minY)].join(' ');

// Turn each letter's drawing instructions into the short text format SVG uses ("M 10 20 C ...").
const pathData = letters.map((l) => ({
  char: l.char,
  d: toPathData(l.path, 1),
  // Keep each letter's own left edge and width (as a share of the whole logo). The motion code
  // does not need these, but they help anyone who wants to line something up with one letter.
  x: round(l.box.x1 - minX),
  width: round(l.box.x2 - l.box.x1),
}));

// The warning printed at the top of both generated files, so nobody edits them by hand.
const stamp = `Generated by scripts/build-wordmark.mjs from Host Grotesk Light (OFL-1.1). Do not edit by hand: change the script and run "npm run wordmark".`;

// ---- File 1: the Astro component -------------------------------------------------------------
// The component below is written out as text. Every page includes it with <Wordmark variant="..."/>.
const pathsMarkup = pathData
  .map(
    (p, i) =>
      `    <path data-letter="${i}" data-char="${p.char}" data-x="${p.x}" data-w="${p.width}" d="${p.d}" />`
  )
  .join('\n');

const component = `---
// Wordmark.astro: the club's logo, the word CIVIC drawn as five shapes, with "AI CLUB" beneath.
// ${stamp}
//
// Each letter is its own <path> with a data-letter number (0 to 4, left to right), so the motion
// code in src/scripts/motion/ can move letters one at a time:
//   - variant="hero":   the huge logo at the top of the home page. The letters rise from both
//                       ends (modules/wordmark.js) and drift apart as you scroll.
//   - variant="footer": the full-width logo at the bottom of every page. It rebuilds from the
//                       center out when the footer comes into view (modules/footer.js).
//   - variant="small":  the little logo the header swaps in (modules/header.js).
//   - variant="plain":  no motion at all (share images, the style guide).
// Screen readers hear one name, "Civic AI Club", because the small "AI CLUB" line is hidden
// from them (it would otherwise be read twice).
interface Props {
  variant?: 'hero' | 'footer' | 'small' | 'plain';
  // Show the small mono "AI CLUB" line under the last C.
  lockup?: boolean;
  // Set to true when the logo sits next to text that already says "Civic AI Club", so screen
  // readers do not hear the name twice.
  decorative?: boolean;
  class?: string;
}
const { variant = 'plain', lockup = true, decorative = false, class: className } = Astro.props;
---

<div class:list={['wordmark', \`wordmark--\${variant}\`, className]} data-wordmark={variant}>
  <svg
    class="wordmark__svg"
    viewBox="${viewBox}"
    role={decorative ? undefined : 'img'}
    aria-label={decorative ? undefined : 'Civic AI Club'}
    aria-hidden={decorative ? 'true' : undefined}
    focusable="false"
  >
${pathsMarkup}
  </svg>
  {lockup && <span class="wordmark__lockup" aria-hidden="true">AI CLUB</span>}
</div>

<style>
  .wordmark {
    display: block;
    width: 100%;
    color: inherit;
  }
  .wordmark__svg {
    display: block;
    width: 100%;
    height: auto;
    overflow: hidden;
    fill: currentColor;
  }
  .wordmark__lockup {
    display: block;
    margin-top: 0.6em;
    text-align: right;
    font-family: var(--font-mono);
    font-size: var(--fs-mono);
    letter-spacing: var(--ls-mono);
    text-transform: uppercase;
    line-height: 1;
  }
  .wordmark--hero .wordmark__lockup {
    font-size: clamp(11px, 0.9vw, 15px);
  }
  .wordmark--small {
    width: auto;
  }
  .wordmark--small .wordmark__svg {
    width: auto;
    height: 0.95em;
  }
</style>
`;

// ---- File 2: a plain SVG copy for the image scripts ------------------------------------------
const svgFile = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" fill="currentColor">
<!-- ${stamp} -->
${pathData.map((p, i) => `<path data-letter="${i}" d="${p.d}"/>`).join('\n')}
</svg>
`;

// Write both files, creating the folders first if they are missing.
const componentPath = resolve(root, 'src/components/Wordmark.astro');
const svgPath = resolve(root, 'src/assets/brand/wordmark.svg');
mkdirSync(dirname(componentPath), { recursive: true });
mkdirSync(dirname(svgPath), { recursive: true });
writeFileSync(componentPath, component);
writeFileSync(svgPath, svgFile);

// Print a short report so whoever ran the script can see it worked.
console.log(`Wordmark: ${WORD} in ${font.names.fontFamily?.en ?? 'Host Grotesk'} Light`);
console.log(`  viewBox ${viewBox}  (width:height = ${(maxX - minX) / (maxY - minY)})`);
console.log(`  wrote ${componentPath}`);
console.log(`  wrote ${svgPath}`);
